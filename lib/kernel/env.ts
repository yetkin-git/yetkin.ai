export type AppEnv = z.infer<typeof envSchema>;

export function parseEnv(source: NodeJS.ProcessEnv = process.env): AppEnv {
  return envSchema.parse(source);
}

let cached: AppEnv | null = null;

export function getEnv(): AppEnv {
  cached ??= parseEnv();
  return cached;
}
