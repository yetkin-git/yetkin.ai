const PROVINCE_BY_FOLD = new Map(
  KURUMSAL_LEAD_PROVINCES.map((name) => [name.toLocaleLowerCase("tr-TR"), name] as const),
);

/**
 * Türkiye 81 il normalizasyonu (D-02).
 * Bilinen il → kanonik ad; bilinmeyen → null.
 */
export function normalizeKurumsalLeadCity(raw: string): string | null {
  const folded = raw.replace(/\s+/g, " ").trim().toLocaleLowerCase("tr-TR");
  if (!folded) {
    return null;
  }
  return PROVINCE_BY_FOLD.get(folded) ?? null;
}
